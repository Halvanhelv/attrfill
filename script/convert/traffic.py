"""How much shoppers search by each attribute: query_clicks.parquet → config/traffic.yml.

    python script/convert/traffic.py data/catalog_dump data/catalog_dump/catalog/all.jsonl data/catalog_dump/full/all.csv

A click is a search query and the product it led to. An attribute counts a click when the query names the
product's value of it ("refrigerator lg 300 l" names brand and volume). The weight of an attribute is its share
of such clicks: Evaluation weighs per-attribute F1 by it, so the fields people filter by count for more.
"""
import csv
import json
import re
import sys
from collections import Counter
from pathlib import Path

import pyarrow.parquet as pq
import yaml

csv.field_size_limit(sys.maxsize)
SKIPPED = {"id", "title", "description", "category"}
WORD = re.compile(r"[a-zа-яё0-9]+(?:[.,][0-9]+)?")


def words(text):
    return [word.replace(",", ".") for word in WORD.findall(text.lower().replace("ё", "е"))]


# A value is named when each of its words is in the query; a long word is matched by its start, as words change endings.
def named(value_words, query):
    return all(word in query if word[0].isdigit() or len(word) < 5 else any(found.startswith(word[:5]) for found in query)
               for word in value_words)


def labels(paths):
    found = {}
    for path in paths:
        rows = (json.loads(line) for line in open(path)) if path.endswith(".jsonl") else csv.DictReader(open(path))
        for row in rows:
            values = {name: words(value) for name, value in row.items()
                      if name not in SKIPPED and value and value.lower() not in {"да", "нет"}}
            found[int(row["id"])] = {name: value for name, value in values.items() if value}
    return found


def main(source, *paths):
    known = labels(paths)
    clicks, named_by = Counter(), Counter()
    queries = {}
    table = pq.ParquetFile(Path(source) / "query_clicks.parquet")
    for batch in table.iter_batches(columns=["sku_id", "toValidUTF8(query_text)"], batch_size=500_000):
        for sku, text in zip(batch.column(0).to_pylist(), batch.column(1).to_pylist()):
            values = known.get(sku)
            if not values:
                continue
            clicks["all"] += 1
            query = queries.get(text)
            if query is None:
                query = queries[text] = set(words(text or ""))
            for name, value in values.items():
                clicks[name] += 1
                if named(value, query):
                    named_by[name] += 1

    total = clicks.pop("all")
    weights = {name: round(named_by[name] / total, 5) for name, _ in named_by.most_common() if named_by[name] >= 20}
    Path("config/traffic.yml").write_text(
        f"# Generated by script/convert/traffic.py: the share of {total} search clicks whose query names the attribute.\n" +
        yaml.safe_dump(weights, allow_unicode=True, sort_keys=False))
    print(f"{total} clicks on labelled cards, {len(weights)} attributes named → config/traffic.yml")
    for name, weight in list(weights.items())[:15]:
        print(f"  {name:30s} {weight}")


if __name__ == "__main__":
    main(*sys.argv[1:])
